    /// Start periodic reflection loop
    pub async fn start(&self) -> Result<()> {
        let mut interval = tokio::time::interval(
            tokio::time::Duration::from_secs(self.audit_interval_secs)
        );

        loop {
            interval.tick().await;
            self.perform_reflection_cycle().await?;
        }
    }

